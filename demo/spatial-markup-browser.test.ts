import assert from 'node:assert/strict';
import test from 'node:test';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import http from 'node:http';
import { chromium } from 'playwright';
import { createDemoServer } from './server.ts';
import { RoomRepository } from '../src/room-model.ts';
import { parseConversationVisual } from '../src/request-conversation.ts';
import type { SpatialMarkup } from '../src/spatial-markup.ts';

test('draw spatial context through the real app, queue it and replay the saved chat', { timeout: 180_000 }, async t => {
  const output = process.env.MARKUP_BROWSER_EVIDENCE ?? await fs.mkdtemp(path.join(os.tmpdir(), 'markup-browser-'));
  await fs.mkdir(output, { recursive: true });
  const backend = await createDemoServer({ backlogFile: path.join(output, 'queue.sqlite') });
  await new Promise<void>(resolve => backend.listen(0, '127.0.0.1', resolve));
  const address = backend.address(); assert.ok(address && typeof address === 'object');
  const assets = path.resolve('dist/demo');
  const front = http.createServer((request, response) => {
    if (request.url?.startsWith('/api/')) {
      const proxy = http.request({ host: '127.0.0.1', port: address.port, method: request.method, path: request.url,
        headers: request.headers }, incoming => { response.writeHead(incoming.statusCode ?? 502, incoming.headers); incoming.pipe(response); });
      proxy.on('error', () => { response.writeHead(502); response.end(); }); request.pipe(proxy); return;
    }
    const filename = request.url === '/' ? 'index.html' : request.url?.slice(1);
    if (!filename || !['index.html', 'room-app.mjs', 'room.css', 'request-chat.css'].includes(filename)) { response.writeHead(404); response.end(); return; }
    response.setHeader('Content-Type', filename.endsWith('.mjs') ? 'text/javascript' : filename.endsWith('.css') ? 'text/css' : 'text/html');
    void fs.readFile(path.join(assets, filename)).then(bytes => response.end(bytes), () => { response.writeHead(404); response.end(); });
  });
  await new Promise<void>(resolve => front.listen(0, '127.0.0.1', resolve));
  const frontAddress = front.address(); assert.ok(frontAddress && typeof frontAddress === 'object');
  const base = `http://127.0.0.1:${frontAddress.port}`;
  const browser = await chromium.launch({ args: ['--no-sandbox', '--disable-dev-shm-usage', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  t.after(async () => { await browser.close(); await new Promise<void>(resolve => front.close(() => resolve()));
    await new Promise<void>(resolve => backend.close(() => resolve())); await backend.closeModelWorkers(); });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 2 });
  page.setDefaultTimeout(15_000);
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  page.on('dialog', dialog => { void dialog.accept(); });
  t.after(async () => { await page.screenshot({ path: path.join(output, 'final.png') }).catch(() => {});
    await fs.writeFile(path.join(output, 'browser-errors.json'), JSON.stringify(errors)); });
  await page.goto(base);
  await page.locator('#project-name').fill('Spatial markup test house');
  await page.locator('#project-template').selectOption('house');
  const created = page.waitForResponse(response => response.url() === base + '/api/projects' && response.request().method() === 'POST');
  await page.locator('#create-project').click();
  const projectValue: unknown = await (await created).json();
  assert.ok(projectValue && typeof projectValue === 'object' && 'project' in projectValue && typeof projectValue.project === 'string');
  const repo = await RoomRepository.restore(projectValue.project); const before = projectValue.project;
  await page.locator('#view-3d').click();
  await page.locator('#workspace-navigation-toggle').click();
  await page.locator('#model-explorer').getByText('Attic', { exact: true }).click();
  if (await page.locator('#show-roof').isChecked()) await page.locator('#show-roof').uncheck();
  await page.waitForFunction(() => document.querySelector('.babylon-viewer')?.getAttribute('data-scene-ready') === 'true');
  assert.equal(await page.locator('canvas:visible').count(), 1);
  const canvas = page.locator('.babylon-viewer canvas'); const controls = page.locator('.model-markup-controls');
  const count = async (expected: number) => { await page.waitForFunction(n => document.querySelector('.model-markup-controls')?.getAttribute('data-markup-count') === String(n), expected); };
  const draw = async (name: string, dx = 100, dy = 60) => {
    if (!await page.getByRole('toolbar', { name: '3D markup tools' }).isVisible()) await page.getByRole('button', { name: '3D markup', exact: true }).click();
    await page.getByRole('button', { name, exact: true }).click();
    const box = await canvas.boundingBox(); assert.ok(box);
    const x = box.x + box.width * .48; const y = box.y + box.height * .63;
    await page.mouse.move(x, y); await page.mouse.down(); await page.mouse.move(x + dx, y + dy, { steps: 12 }); await page.mouse.up();
  };
  await draw('Rectangle'); await count(1);
  await page.screenshot({ path: path.join(output, 'rectangle.png') });
  const chip = await page.locator('.composer-context-chip').allTextContents(); assert.ok(chip.some(text => text.includes('Rectangle')));
  const box = await canvas.boundingBox(); assert.ok(box);
  await page.mouse.move(box.x + box.width * .6, box.y + box.height * .65); await page.mouse.down();
  await page.mouse.move(box.x + box.width * .7, box.y + box.height * .66, { steps: 8 }); await page.mouse.up(); await count(1);
  await draw('Circle', 70, 20); await count(2);
  await draw('Line', -70, 35); await count(3);
  // Toolbar remains open after drawing; exercise explicit undo and cancel without losing attached shapes.
  await page.getByRole('button', { name: 'Undo markup', exact: true }).click(); await count(2);
  await page.getByRole('button', { name: 'Line', exact: true }).click();
  await canvas.press('Escape'); await count(2);
  assert.equal(await controls.getAttribute('data-tool'), 'select');
  await page.getByRole('button', { name: 'Polyline', exact: true }).click();
  await page.mouse.click(box.x + box.width * .45, box.y + box.height * .65);
  await page.mouse.click(box.x + box.width * .50, box.y + box.height * .68);
  await page.mouse.click(box.x + box.width * .55, box.y + box.height * .65);
  await page.getByRole('button', { name: 'Finish polyline', exact: true }).click(); await count(3);
  await page.getByRole('button', { name: 'Undo markup', exact: true }).click(); await count(2);
  await page.locator('#request-text').fill('Add a kitchen here, using the rectangle as the intended area.');
  const submitted = page.waitForResponse(response => response.url() === base + '/api/change-requests' && response.request().method() === 'POST');
  await page.locator('#save-proposal').click(); const submittedResponse = await submitted; assert.equal(submittedResponse.status(), 202);
  const payload: unknown = submittedResponse.request().postDataJSON();
  assert.ok(payload && typeof payload === 'object' && 'request' in payload && payload.request && typeof payload.request === 'object');
  assert.ok('conversationVisual' in payload.request && 'selectedObjectIds' in payload.request);
  const saved = parseConversationVisual(payload.request.conversationVisual);
  assert.equal(saved.annotations.length, 2); assert.deepEqual(saved.selectedObjectIds, []);
  assert.ok(!JSON.stringify(payload.request.selectedObjectIds).includes('door'), 'A highlighted door must not become the region anchor.');
  const shapes: SpatialMarkup[] = saved.annotations.filter(shape => shape.kind !== 'pin' && shape.kind !== 'arrow');
  assert.equal(shapes[0]?.kind, 'rectangle'); assert.equal(shapes[1]?.kind, 'circle');
  assert.equal(saved.levelId, 'level-attic');
  if (shapes[0]?.kind === 'rectangle') assert.ok(shapes[0].corners.every(point => Math.abs(point[2] - 3) < .00001));
  await page.waitForFunction(() => document.querySelector('.model-markup-controls')?.getAttribute('data-reference-markup-count') === '2');
  const visualDetails = page.locator('#request-chat .request-chat-visual');
  await visualDetails.locator('summary').click();
  assert.match(await visualDetails.innerText(), /rectangle.*Corners.*approximate user intent/i);
  assert.match(await visualDetails.innerText(), /circle.*Centre.*approximate user intent/i);
  await page.screenshot({ path: path.join(output, 'saved-chat.png') });
  const stored = await page.request.get(base + '/api/projects/' + repo.projectId); const after: unknown = await stored.json();
  assert.ok(after && typeof after === 'object' && 'project' in after); assert.equal(after.project, before);
  await page.locator('#new-chat').click(); await count(0);
  assert.equal(await controls.getAttribute('data-reference-markup-count'), '0');
  await page.locator('#chat-switcher-button').click();
  await page.locator('.chat-switcher-item').filter({ hasText: 'Add a kitchen here' }).click();
  await page.waitForFunction(() => document.querySelector('.model-markup-controls')?.getAttribute('data-reference-markup-count') === '2');
  await fs.writeFile(path.join(output, 'context.json'), JSON.stringify({ saved, acceptedProjectUnchanged: true, errors }, null, 2));
  assert.deepEqual(errors, []);
});
