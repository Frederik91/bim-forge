import assert from 'node:assert/strict';
import test from 'node:test';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { chromium } from 'playwright';
import { createDemoServer } from './server.ts';
import { RoomRepository } from '../src/room-model.ts';
import { planFixture } from './model-plan-fixture.ts';

test('shipped native workspace preserves Inside pose, draft, selection and canvas through Plan and Overview', { timeout: 90_000 }, async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'plan-integration-256-'));
  const server = await createDemoServer({ backlogFile: path.join(directory, 'queue.sqlite') });
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
  const address = server.address(); assert.ok(address && typeof address === 'object');
  const browser = await chromium.launch({ headless: true, args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const artifacts = process.env.PLAN_INTEGRATION_ARTIFACTS ?? 'artifacts/plan-integration-256'; await fs.mkdir(artifacts, { recursive: true });
  t.after(async () => { t.diagnostic(JSON.stringify({ errors, status: await page.locator('#status').textContent(), error: await page.locator('#error').textContent() })); await browser.close(); await new Promise<void>(resolve => server.close(() => resolve())); await server.closeModelWorkers(); await fs.rm(directory, { recursive: true, force: true }); });
  await page.goto(`http://127.0.0.1:${address.port}`);
  await page.locator('#project-template').selectOption('house');
  await page.locator('#project-name').fill('Native spatial workspace qualification'); await page.locator('#create-project').click();
  await page.locator('#open-chat').click();
  await page.waitForFunction(() => document.getElementById('workspace-shell')?.dataset.spatialView === 'inside');
  const canvas = page.locator('canvas.model-canvas'); await canvas.waitFor();
  const originalCanvas = await canvas.elementHandle(); assert.ok(originalCanvas);
  const capture = () => page.evaluate(async () => { const url = '/room-app.mjs'; const api = await import(url); return api.captureWorkspaceInsidePose(); });
  const first = await capture(); assert.ok(first); assert.equal(first.motion, 'walk');
  await page.locator('#request-text').fill('Keep this unsent door task through every view');
  const selection = await page.locator('#selected-object').inputValue();
  await canvas.focus(); await page.keyboard.down('w'); await page.waitForTimeout(250); await page.keyboard.up('w');
  const moved = await capture(); assert.ok(moved); assert.notDeepEqual(moved.eye, first.eye);
  await page.locator('#view-plan').click();
  const svg = page.locator('#proposal-drawing > svg'); await svg.waitFor();
  assert.equal(await svg.getAttribute('data-level-id'), first.levelId);
  assert.equal(await page.locator('#request-text').inputValue(), 'Keep this unsent door task through every view');
  assert.equal(await page.locator('#selected-object').inputValue(), selection);
  const source = await svg.getAttribute('data-revision-id'); assert.ok(source);
  const metric = await svg.locator('text').allTextContents(); assert.ok(metric.some(text => text.includes('mm'))); assert.ok(metric.some(text => text.includes('m²')));
  await page.waitForFunction(() => { const node = document.querySelector('#proposal-drawing > svg text'); return node && getComputedStyle(node).fontSize === '13px'; });
  const textSize = await page.evaluate(() => { const node = document.querySelector('#proposal-drawing > svg text'); return node ? getComputedStyle(node).fontSize : ''; }); assert.equal(textSize, '13px');
  await page.screenshot({ path: path.join(artifacts, 'desktop-plan.png'), fullPage: true });
  await page.locator('#view-3d').click(); await canvas.waitFor();
  await page.locator('#view-inside').click();
  const returned = await capture(); assert.deepEqual(returned, moved);
  assert.equal(await canvas.evaluate((node, other) => node === other, originalCanvas), true);
  await page.locator('#request-text').focus(); await page.keyboard.down('w'); await page.waitForTimeout(120); await page.keyboard.up('w');
  assert.deepEqual(await capture(), returned, 'Typing cannot move the camera');
  await page.locator('#view-fly').click(); const fly = await capture(); assert.equal(fly?.motion, 'fly');
  await canvas.focus(); await page.keyboard.down('Shift'); await page.waitForTimeout(200); await page.keyboard.up('Shift');
  const up = await capture(); assert.ok(up.eye[2] > fly.eye[2]);
  await page.keyboard.press('Space'); assert.deepEqual(await capture(), up, 'Space does not ascend');
  await page.locator('#mouse-look').click(); await page.keyboard.press('Escape');
  const stopped = await capture(); await page.keyboard.down('w'); await page.waitForTimeout(100); await page.keyboard.up('w');
  // Escape releases movement; focus remains explicit in the model for later navigation.
  await page.locator('#request-text').focus(); const focusStop = await capture(); await page.waitForTimeout(100); assert.deepEqual(await capture(), focusStop);
  await page.screenshot({ path: path.join(artifacts, 'desktop-inside.png'), fullPage: true });
  await page.locator('#view-plan').click();
  await page.setViewportSize({ width: 390, height: 900 });
  await page.waitForTimeout(250);
  assert.equal(await page.evaluate(() => { const node = document.querySelector('#proposal-drawing > svg text'); const m = node instanceof SVGGraphicsElement ? node.getScreenCTM() : null; return m && node ? Math.round(Number.parseFloat(getComputedStyle(node).fontSize) * m.a) : 0; }), 13);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  await page.screenshot({ path: path.join(artifacts, 'narrow-plan.png'), fullPage: true });
  assert.deepEqual(errors, []); assert.ok(stopped);
  const fixture = planFixture(); assert.ok(fixture.comparison);
  const accepted = await RoomRepository.createProject({ projectId: crypto.randomUUID(), name: 'Native width comparison', snapshot: fixture.comparison.snapshot });
  const proposal = await accepted.propose({ name: 'widened', from: accepted.head('main'), doorWidthM: 1.1 });
  const imported = await page.request.post(`http://127.0.0.1:${address.port}/api/projects`, { data: { project: proposal.serialize() } });
  assert.equal(imported.status(), 200);
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const comparisonPage = await context.newPage();
  await comparisonPage.goto(`http://127.0.0.1:${address.port}`);
  await comparisonPage.getByText('Project tools', { exact: false }).first().click(); await comparisonPage.locator('#new-project').click();
  await comparisonPage.locator('#saved-projects').selectOption(proposal.projectId); await comparisonPage.locator('#open-saved-project').click();
  await comparisonPage.locator('#nav-history').click(); await comparisonPage.locator('.history-button[data-branch="widened"]').click();
  await comparisonPage.locator('#view-plan').click();
  const drawing = comparisonPage.locator('#proposal-drawing > svg');
  await drawing.getByText('900 → 1100 mm', { exact: true }).waitFor();
  assert.equal(await drawing.getAttribute('data-revision-id'), proposal.head('widened'));
  const oldDoor = drawing.locator('[data-entity-id="door-entry"][data-revision-role="existing"]').first();
  assert.equal(await oldDoor.getAttribute('data-revision-id'), accepted.head('main'));
  assert.equal(await drawing.locator('[data-entity-id="level-ground-wall-north"][data-revision-role="existing"]').count(), 0, 'Unchanged walls have no ghost');
  await oldDoor.focus(); await comparisonPage.keyboard.press('Enter');
  await comparisonPage.getByText(`Existing revision ${accepted.head('main').slice(0, 10)}`, { exact: false }).first().waitFor();
  await comparisonPage.waitForFunction(() => { const root = document.querySelector('#proposal-drawing > svg'); return root instanceof SVGSVGElement && Math.abs(root.viewBox.baseVal.width - root.clientWidth) < 1 && Math.abs(root.viewBox.baseVal.height - root.clientHeight) < 1; });
  await comparisonPage.locator('#workspace-navigation-toggle').focus();
  const zoomScale = () => comparisonPage.evaluate(async () => { const url = '/room-app.mjs'; const api = await import(url); return api.getWorkspacePlanContext(document.querySelector('#proposal-drawing > svg'))?.projection.pixelsPerMetre; });
  const beforeScale = await zoomScale();
  const box = await drawing.boundingBox(); assert.ok(box);
  const beforeZoom = await drawing.getAttribute('viewBox');
  await comparisonPage.screenshot({ path: path.join(artifacts, 'native-1100-comparison.png'), fullPage: true });
  await comparisonPage.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await comparisonPage.mouse.wheel(0, -240);
  await comparisonPage.waitForTimeout(150);
  assert.equal(await drawing.getAttribute('viewBox'), beforeZoom, 'Zoom rerenders engineering bounds without scaling screen units');
  assert.ok(await zoomScale() > beforeScale, 'Wheel zoom changes the actual engineering projection');
  assert.equal(await comparisonPage.evaluate(() => { const node = document.querySelector('#proposal-drawing > svg text'); const m = node instanceof SVGGraphicsElement ? node.getScreenCTM() : null; return m && node ? Math.round(Number.parseFloat(getComputedStyle(node).fontSize) * m.a) : 0; }), 13);
  const acceptedDoor = accepted.view(accepted.head('main')).snapshot.entities.find(item => item.id === 'door-entry');
  assert.ok(acceptedDoor?.type === 'Door'); assert.equal(acceptedDoor.width, .9);
  const bounds = () => comparisonPage.evaluate(async () => { const url = '/room-app.mjs'; const api = await import(url); return api.getWorkspacePlanContext(document.querySelector('#proposal-drawing > svg'))?.projection.bounds; });
  const beforePan = await bounds();
  await comparisonPage.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await comparisonPage.keyboard.down('Shift');
  await comparisonPage.mouse.down(); await comparisonPage.mouse.move(box.x + box.width / 2 + 30, box.y + box.height / 2, { steps: 3 }); await comparisonPage.mouse.up(); await comparisonPage.keyboard.up('Shift');
  assert.ok((await bounds()).minX < beforePan.minX, 'Shift drag pans actual project bounds');
  await context.close();
});
