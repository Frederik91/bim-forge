import assert from 'node:assert/strict';
import test from 'node:test';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { chromium } from 'playwright';
import { createDemoServer } from './server.ts';
import { spatialFixtureWorker, spatialWorkerGate } from '../tests/fixtures/spatial-workspace/worker.ts';
import { SpatialTasks } from './spatial-tasks.ts';
import { RoomRepository } from '../src/room-model.ts';
import { parseTaskPlacement } from '../src/task-placement.ts';

test('Overview dispatch puts real door and wall task bodies beside geometry, visible and pickable without changing the model', { timeout: 120_000 }, async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'agent-placement-305-'));
  const artifacts = process.env.AGENT_PLACEMENT_ARTIFACTS ?? path.join(directory, 'evidence'); await fs.mkdir(artifacts, { recursive: true });
  const gate = spatialWorkerGate();
  const server = await createDemoServer({ modelWorker: spatialFixtureWorker({ mode: 'region-context', afterScript: session => gate.afterScript(session) }), backlogFile: path.join(directory, 'queue.sqlite') });
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
  const address = server.address(); assert.ok(address && typeof address === 'object'); const base = `http://127.0.0.1:${address.port}`;
  const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  t.after(async () => {
    gate.release();
    await page.screenshot({ path: path.join(artifacts, 'last.png'), fullPage: true });
    t.diagnostic(JSON.stringify({ errors, status: await page.locator('#status').textContent(), error: await page.locator('#error').textContent() }));
    await browser.close(); await new Promise<void>(resolve => server.close(() => resolve())); await server.closeModelWorkers();
    await fs.rm(directory, { recursive: true, force: true });
  });
  const parser = new SpatialTasks();
  const ready = (mode: 'personal' | 'task') => page.waitForFunction(expected => document.getElementById('workspace-context')?.dataset.assistantMode === expected
    && !document.querySelector<HTMLTextAreaElement>('#request-text')?.disabled, mode);
  const submit = async (selectedId: string) => {
    await page.locator('.model-object-picker').selectOption(selectedId);
    await page.locator('#request-text').fill(`Inspect the selected ${selectedId}; keep the model unchanged.`);
    const sent = page.waitForResponse(response => response.url() === `${base}/api/change-requests` && response.request().method() === 'POST');
    await page.getByRole('button', { name: 'Send message', exact: true }).click();
    const response = await sent; assert.equal(response.status(), 202);
    const value: unknown = await response.json(); assert.ok(value && typeof value === 'object' && 'ticket' in value);
    const ticket = parser.parseTicket(value.ticket); assert.deepEqual(ticket.request.selectedObjectIds, [selectedId]);
    await ready('personal'); return ticket;
  };
  const pick = async (id: string) => {
    await page.locator('#workspace-context-close').click();
    const label = page.locator(`.spatial-task-label[data-task-id="${id}"]`); await label.waitFor({ state: 'visible' });
    const body = await label.evaluate(node => ({ x: Number(node.dataset.bodyX), y: Number(node.dataset.bodyY) }));
    const canvas = await page.locator('canvas.model-canvas').boundingBox(); assert.ok(canvas);
    await page.screenshot({ path: path.join(artifacts, `${id}.png`), fullPage: true });
    await page.mouse.click(canvas.x + body.x, canvas.y + body.y); await ready('task');
    const hit: unknown = JSON.parse(await page.locator('.babylon-viewer').getAttribute('data-task-hit') ?? '{}');
    assert.ok(hit && typeof hit === 'object' && 'kind' in hit && hit.kind === 'task' && 'identity' in hit && hit.identity && typeof hit.identity === 'object' && 'ticketId' in hit.identity);
    assert.equal(hit.identity.ticketId, id, 'The actual model-space figure receives the body ray pick');
  };
  await page.goto(base); await page.locator('#project-template').selectOption('house');
  await page.locator('#project-name').fill('Agents beside selected geometry'); await page.locator('#create-project').click();
  await page.locator('#open-chat').click(); await page.getByRole('button', { name: 'Basic', exact: true }).click();
  await page.locator('#view-overview').click(); await page.locator('.babylon-viewer[data-scene-ready="true"]').waitFor();
  await page.waitForFunction(() => document.getElementById('workspace-shell')?.dataset.spatialView === 'overview');
  assert.equal(await page.evaluate(async () => { const url = '/room-app.mjs'; return (await import(url)).captureWorkspaceInsidePose(); }), null);
  const canvas = await page.locator('canvas.model-canvas').elementHandle(); assert.ok(canvas);
  const door = await submit('level-ground-door-inner');
  const baseline = await (await page.request.get(`${base}/api/projects/${door.projectId}`)).json();
  assert.ok(baseline && typeof baseline === 'object' && 'project' in baseline && typeof baseline.project === 'string');
  const repository = RoomRepository.restore(baseline.project); const graph = repository.view(repository.head('main')).snapshot;
  const placement = parseTaskPlacement(door.taskPlacement); assert.equal(placement.kind, 'placed'); if (placement.kind !== 'placed') return;
  const host = graph.relationships.find(link => link.source === 'level-ground-door-inner'); assert.ok(host);
  const wall = graph.entities.find(entity => entity.id === host.target); assert.ok(wall?.type === 'Wall');
  assert.ok(Math.abs(placement.origin.point[0] - wall.start[0]) >= wall.thickness / 2 + .44, 'Door agent clears the inner wall even though Overview has no Inside eye');
  assert.ok(Math.abs(placement.origin.point[1] - host.offset - .45) >= .74, 'Door figure is beside the jamb instead of centred on the leaf');
  await pick(door.id);
  await page.locator('#open-chat').click(); await ready('personal');
  const wallTask = await submit('level-ground-wall-inner');
  const wallPlacement = parseTaskPlacement(wallTask.taskPlacement); assert.equal(wallPlacement.kind, 'placed'); if (wallPlacement.kind !== 'placed') return;
  assert.ok(Math.abs(wallPlacement.origin.point[0] - wall.start[0]) >= wall.thickness / 2 + .44);
  await pick(wallTask.id);
  assert.equal(await canvas.evaluate(node => node.isConnected), true); assert.equal(await page.locator('canvas').count(), 1);
  assert.deepEqual(await (await page.request.get(`${base}/api/projects/${door.projectId}`)).json(), baseline);
  await page.reload();
  const after: unknown = await (await page.request.get(`${base}/api/change-requests/${door.id}`)).json(); assert.ok(after && typeof after === 'object' && 'ticket' in after);
  assert.deepEqual(parseTaskPlacement(parser.parseTicket(after.ticket).taskPlacement), placement, 'Reload never relocates the dispatched agent');
  assert.deepEqual(await (await page.request.get(`${base}/api/projects/${door.projectId}`)).json(), baseline); assert.deepEqual(errors, []);
  await fs.writeFile(path.join(artifacts, 'result.json'), JSON.stringify({ door: placement, wall: wallPlacement, exactBodyPicks: 2, unchangedModel: true, errors }, null, 2));
});
