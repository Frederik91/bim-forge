import { clickConversationControl } from '../tests/fixtures/spatial-workspace/browser.ts';
import assert from 'node:assert/strict';
import test from 'node:test';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { chromium } from 'playwright';
import { createDemoServer } from './server.ts';
import { RoomRepository } from '../src/room-model.ts';
import { parseTaskPlacement } from '../src/task-placement.ts';
import type { ModelWorker } from '../src/model-proposal.ts';
import { spatialFixtureWorker, spatialWorkerGate } from '../tests/fixtures/spatial-workspace/worker.ts';
import { spatialFixtureManifest } from '../tests/fixtures/spatial-workspace/fixture.ts';
import { SpatialTasks } from './spatial-tasks.ts';
import { taskDispatchPoint } from './task-dispatch.ts';
import { conversationMarkups } from './request-chat-evidence.ts';
import { parseRequestConversation } from '../src/request-conversation.ts';

test('personal assistant dispatches a marked-area agent while the door agent works, then uses current eye with no reference', { timeout: 150_000 }, async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'spatial-dispatch-295-'));
  const gate = spatialWorkerGate();
  const door = spatialFixtureWorker({ afterScript: session => gate.afterScript(session) });
  const region = spatialFixtureWorker({ mode: 'region-context' });
  let runs = 0;
  const worker: ModelWorker = { identity: door.identity, run: session => (++runs === 1 ? door : region).run(session) };
  const server = await createDemoServer({ modelWorker: worker, backlogFile: path.join(directory, 'queue.sqlite') });
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
  const address = server.address(); assert.ok(address && typeof address === 'object'); const base = `http://127.0.0.1:${address.port}`;
  const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  t.after(async () => {
    gate.release();
    t.diagnostic(JSON.stringify({ errors, status: await page.locator('#status').textContent(), error: await page.locator('#error').textContent() }));
    t.diagnostic(JSON.stringify({ pose: await page.evaluate(async () => {
      const url = '/room-app.mjs'; const pose = (await import(url)).captureWorkspaceInsidePose();
      return pose ? { eye: pose.eye, forward: pose.forward, up: pose.up, levelId: pose.levelId, motion: pose.motion } : null;
    }) }));
    if (process.env.SPATIAL_DISPATCH_ARTIFACTS) { await fs.mkdir(process.env.SPATIAL_DISPATCH_ARTIFACTS, { recursive: true }); await page.screenshot({ path: path.join(process.env.SPATIAL_DISPATCH_ARTIFACTS, 'last.png'), fullPage: true }); }
    await browser.close(); await new Promise<void>(resolve => server.close(() => resolve())); await server.closeModelWorkers();
    await fs.rm(directory, { recursive: true, force: true });
  });
  const parser = new SpatialTasks();
  const mode = (expected: 'personal' | 'task') => page.waitForFunction(value => {
    const field = document.getElementById('request-text'); return document.getElementById('workspace-context')?.dataset.assistantMode === value
      && field instanceof HTMLTextAreaElement && !field.disabled;
  }, expected);
  const capture = () => page.evaluate(async () => { const url = '/room-app.mjs'; return (await import(url)).captureWorkspaceInsidePose(); });
  const read = async (id: string) => {
    const value: unknown = await (await page.request.get(`${base}/api/change-requests/${id}`)).json();
    assert.ok(value && typeof value === 'object' && 'ticket' in value); return value.ticket;
  };
  const submit = async (text: string) => {
    await page.locator('#request-text').fill(text);
    const response = page.waitForResponse(value => value.url() === `${base}/api/change-requests` && value.request().method() === 'POST');
    await page.getByRole('button', { name: 'Send message', exact: true }).click();
    const acknowledgement = await response; assert.equal(acknowledgement.status(), 202, await acknowledgement.text());
    const value: unknown = await acknowledgement.json(); assert.ok(value && typeof value === 'object' && 'ticket' in value);
    await mode('personal');
    return parser.parseTicket(value.ticket);
  };
  await page.goto(base); await page.locator('#project-template').selectOption('house'); await page.locator('#project-name').fill('Personal assistant dispatch'); await page.locator('#create-project').click();
  await page.locator('#open-chat').click(); await page.getByRole('button', { name: 'Basic', exact: true }).click();
  await page.locator('.babylon-viewer[data-scene-ready="true"]').waitFor();
  assert.equal(await page.locator('.spatial-task-label').count(), 0, 'The personal assistant is not a stationary task figure');
  await page.locator('.model-object-picker').selectOption(spatialFixtureManifest.doorId);
  const firstEye = await capture(); assert.ok(firstEye);
  const a = await submit('Widen this door to 1100 mm, keeping its centre.');
  await gate.reached;
  assert.equal(parser.parseTicket(await read(a.id)).state, 'working');
  assert.equal(await page.locator('#request-text').inputValue(), '');
  assert.equal(await page.locator('#workspace-context').getAttribute('data-assistant-mode'), 'personal');
  assert.equal(await page.locator('.spatial-task-label').count(), 1);
  const baseline = await (await page.request.get(`${base}/api/projects/${a.projectId}`)).json();
  assert.ok(baseline && typeof baseline === 'object' && 'project' in baseline && typeof baseline.project === 'string');
  const accepted = await RoomRepository.restore(baseline.project); const graph = accepted.view(accepted.head('main')).snapshot;
  const firstPlacement = parseTaskPlacement(a.taskPlacement); assert.equal(firstPlacement.kind, 'placed');
  if (firstPlacement.kind !== 'placed') return;
  assert.deepEqual(firstPlacement.origin.point, taskDispatchPoint({ graph, selectedObjectIds: [spatialFixtureManifest.doorId], markups: [], eye: firstEye.eye }));
  await page.evaluate(async () => {
    const url = '/room-app.mjs'; const api = await import(url); const pose = api.captureWorkspaceInsidePose();
    if (!pose || !api.returnWorkspaceToPose({ ...pose, eye: [6, 3, 1.6], forward: [0, 1, 0], up: [0, 0, 1], motion: 'fly' })) throw new Error('Fixture cannot enter east room');
  });
  await page.getByRole('button', { name: '3D markup', exact: true }).click(); await page.getByRole('button', { name: 'Rectangle', exact: true }).click();
  const canvas = page.locator('canvas.model-canvas'); const box = await canvas.boundingBox(); assert.ok(box);
  const x = box.x + box.width * .25; const y = box.y + box.height * .76;
  await page.mouse.move(x, y); await page.mouse.down(); await page.mouse.move(x + 100, y + 45, { steps: 10 }); await page.mouse.up();
  await page.waitForFunction(() => document.querySelector('.model-markup-controls')?.getAttribute('data-markup-count') === '1');
  assert.equal(await page.locator('.spatial-task-label').count(), 1, 'Drawing context does not spawn a task yet');
  const b = await submit('Assign a separate task to the area I outlined in this room.');
  assert.notEqual(a.id, b.id); assert.equal(parser.parseTicket(await read(a.id)).state, 'working');
  assert.deepEqual(parser.parseTicket(await read(a.id)).taskPlacement, firstPlacement);
  const secondPlacement = parseTaskPlacement(b.taskPlacement); assert.equal(secondPlacement.kind, 'placed');
  if (secondPlacement.kind !== 'placed') return;
  assert.equal(secondPlacement.targets.regions.length, 1); assert.deepEqual(secondPlacement.targets.objects, []);
  const detail = await read(b.id); assert.ok(detail && typeof detail === 'object' && 'conversation' in detail);
  const conversation = parseRequestConversation(detail.conversation); const initial = conversation.messages.find(message => message.kind === 'user');
  const markups = initial?.kind === 'user' ? conversationMarkups(initial.visual) : [];
  assert.deepEqual(secondPlacement.origin.point, taskDispatchPoint({ graph, selectedObjectIds: [], markups, eye: [6, 3, 1.6] }));
  assert.notDeepEqual(secondPlacement.origin.point, firstPlacement.origin.point);
  const fallbackEye = await capture(); assert.ok(fallbackEye);
  const c = await submit('Explore a new task here without a selected object.');
  const thirdPlacement = parseTaskPlacement(c.taskPlacement); assert.equal(thirdPlacement.kind, 'placed');
  if (thirdPlacement.kind !== 'placed') return;
  assert.deepEqual(thirdPlacement.targets, { objects: [], regions: [] }); assert.deepEqual(thirdPlacement.origin.point, fallbackEye.eye);
  await page.locator('.model-object-picker').selectOption('level-ground-wall-east');
  await page.locator('#request-text').fill('Keep this personal instruction unsent.');
  const uploadHeld = Promise.withResolvers<void>(); const releaseUpload = Promise.withResolvers<void>(); const uploadFinished = Promise.withResolvers<void>();
  t.after(() => releaseUpload.resolve());
  await page.route(`${base}/api/projects/${a.projectId}/sources/*`, async route => {
    if (route.request().method() !== 'POST') { await route.continue(); return; }
    const saved = await route.fetch(); uploadHeld.resolve(); await releaseUpload.promise; await route.fulfill({ response: saved }); uploadFinished.resolve();
  }, { times: 1 });
  await page.locator('#request-source-files').setInputFiles({ name: 'personal-context.txt', mimeType: 'text/plain', buffer: Buffer.from('Keep this pending attachment with the personal instruction.') });
  await uploadHeld.promise;
  await page.getByRole('button', { name: 'Tasks', exact: true }).click(); await page.locator(`#spatial-task-list [data-task-id="${a.id}"]`).click();
  await mode('task');
  releaseUpload.resolve(); await uploadFinished.promise;
  assert.doesNotMatch(await page.locator('#request-source-list').innerText(), /personal-context/);
  await page.locator('#request-text').fill('Keep this follow-up on the first agent.');
  const beforeReturn = await capture();
  await clickConversationControl(page, '#personal-assistant');
  await mode('personal');
  assert.equal(await page.locator('#request-text').inputValue(), 'Keep this personal instruction unsent.');
  await page.getByText('1 of 4 files ready', { exact: true }).waitFor();
  assert.match(await page.locator('#request-source-list').innerText(), /personal-context/);
  assert.equal(await page.locator('.model-object-picker').inputValue(), 'level-ground-wall-east');
  const afterReturn = await capture(); assert.ok(beforeReturn && afterReturn);
  assert.deepEqual(afterReturn.eye, beforeReturn.eye); assert.deepEqual(afterReturn.forward, beforeReturn.forward);
  await page.getByRole('button', { name: 'Tasks', exact: true }).click(); await page.locator(`#spatial-task-list [data-task-id="${a.id}"]`).click();
  await mode('task');
  assert.equal(await page.locator('#request-text').inputValue(), 'Keep this follow-up on the first agent.');
  await clickConversationControl(page, '#personal-assistant'); await mode('personal'); gate.release(); await gate.finished;
  assert.equal(await page.locator('#workspace-context').getAttribute('data-assistant-mode'), 'personal');
  assert.equal(await page.locator('.spatial-task-label').count(), 3, 'Only the three submitted tasks have figures');
  await page.locator('#new-chat').click();
  await mode('personal');
  await page.locator('.model-object-picker').selectOption('level-ground-wall-east');
  const wallTask = await submit('Inspect this east wall as a separate task.');
  assert.deepEqual(wallTask.request.selectedObjectIds, ['level-ground-wall-east']);
  await page.evaluate(async () => {
    const url = '/room-app.mjs'; const api = await import(url); const pose = api.captureWorkspaceInsidePose(); const n = Math.sqrt(1.25);
    if (!pose || !api.returnWorkspaceToPose({ ...pose, eye: [6, 3, 1.6], forward: [1 / n, 0, -.5 / n], up: [.5 / n, 0, 1 / n], motion: 'fly' })) throw new Error('Cannot face wall task');
  });
  const wallLabel = page.locator(`.spatial-task-label[data-task-id="${wallTask.id}"]`); await wallLabel.waitFor({ state: 'visible' });
  const body = await wallLabel.evaluate(node => ({ x: Number(node.dataset.bodyX), y: Number(node.dataset.bodyY) }));
  const wallCanvas = await canvas.boundingBox(); assert.ok(wallCanvas);
  await page.mouse.click(wallCanvas.x + body.x, wallCanvas.y + body.y); await mode('task');
  const hit: unknown = JSON.parse(await page.locator('.babylon-viewer').getAttribute('data-task-hit') ?? '{}');
  assert.ok(hit && typeof hit === 'object' && 'kind' in hit && hit.kind === 'task' && 'identity' in hit && hit.identity && typeof hit.identity === 'object' && 'ticketId' in hit.identity);
  assert.equal(hit.identity.ticketId, wallTask.id, 'The actual wall agent body is visible and pickable in front of its host');
  assert.deepEqual(await (await page.request.get(`${base}/api/projects/${a.projectId}`)).json(), baseline);
  assert.deepEqual(errors, []);
});
